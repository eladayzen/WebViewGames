  PATTERN_DESCENT_HARD_CAP,
  MODES,
  DENSITY_CAPS,
  POC_ENEMY_CAP_OVERRIDE,
  ENEMY,
  enemyDef,
  BOSS,
  INPUT,
  FORMATIONS,
  FORMATION_X,
